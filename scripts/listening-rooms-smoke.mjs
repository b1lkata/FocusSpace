import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdirSync } from 'node:fs';
const output = '.runtime/listening-rooms';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 920 } });
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4173');
  await page.getByRole('button', { name: 'Room lamp', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Room lamp', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await page.getByRole('button', { name: 'Grow room plant' }).click();
  await expect(page.locator('.room-plant')).toHaveClass(/plant-grown/);
  await page.screenshot({ path: `${output}/cozy.png` });
  await page.getByRole('button', { name: 'night room', exact: true }).click();
  await page.getByRole('button', { name: 'Make a wish' }).click();
  await expect(page.locator('.listening-room')).toHaveClass(/room-wish/);
  await page.screenshot({ path: `${output}/night.png` });
  await page.getByRole('button', { name: 'neon room', exact: true }).click();
  await expect(page.locator('.room-neon-sign')).toBeVisible();
  await page.getByRole('button', { name: 'Room lamp', exact: true }).click();
  await page.screenshot({ path: `${output}/neon.png` });
  await page.reload();
  await expect(page.getByRole('button', { name: 'neon room', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Less detail' }).click();
  await expect(page.locator('.room-neon-sign')).toBeHidden();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Show details' })).toBeVisible();
  await page.getByRole('button', { name: 'Show details' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Room lamp', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `${output}/phone.png`, fullPage: true });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.locator('.lamp-glow').evaluate(el => getComputedStyle(el).animationName)).toBe('none');
  const accessibility = await new AxeBuilder({ page }).include(".music-hero").analyze();
  expect(accessibility.violations).toEqual([]);
  expect(errors).toEqual([]);
  console.log('PASS room interactions, persistence, mobile layout, reduced motion and accessibility. Public network deliberately blocked.');
} finally { await browser.close(); }
